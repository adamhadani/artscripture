import Foundation
import Testing

@testable import AudioDecode

// A video file is opened for its soundtrack. Nothing about the picture is read,
// drawn or kept: the decoder asks AVFoundation for audio tracks only, so the
// question each test here asks is whether *that* is true of a real movie file —
// one with an H.264 picture track sitting beside the sound.
//
// These run on the iPad simulator as well as the Mac (`AudioDecodeTests` is in
// the portable bundle), which is the point: the file picker offers these three
// containers on every platform, so every platform has to prove it decodes them.

private func fixture(_ name: String) -> URL {
    URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()  // AudioDecodeTests
        .deletingLastPathComponent()  // Tests
        .appendingPathComponent("Fixtures")
        .appendingPathComponent(name)
}

/// The dominant frequency of channel 0, from zero crossings over the middle of
/// the file — away from the encoder's priming and the fade at the end, either of
/// which would add crossings that are not the tone.
private func dominantFrequency(_ audio: DecodedAudio) -> Double {
    let samples = audio.channel(0)
    let frames = Int(audio.frameCount)
    let start = frames / 4
    let end = frames - frames / 4
    var crossings = 0
    for i in (start + 1)..<end where (samples[i - 1] < 0) != (samples[i] < 0) {
        crossings += 1
    }
    let seconds = Double(end - start) / audio.sampleRate
    return Double(crossings) / 2 / seconds
}

/// Generated by `Tests/Fixtures/generate.sh`: the same 2 s, 440 Hz stereo tone
/// as `sine.m4a`, under a 16×16 black H.264 picture, in each container the
/// picker offers.
@Test(arguments: ["sine_video.mp4", "sine_video.mov", "sine_video.m4v"])
func decodesTheSoundtrackOfAVideo(name: String) async throws {
    let audio = try await AudioFileDecoder.decode(url: fixture(name))
    #expect(audio.channels == 2)
    #expect(audio.sampleRate == 44100)
    #expect(audio.frameCount > 44100, "\(name): \(audio.frameCount) frames, owed ~2 s")

    let ch = audio.channel(0)
    var peak: Float = 0
    for i in 0..<Int(audio.frameCount) { peak = max(peak, abs(ch[i])) }
    #expect(peak > 0.3, "\(name): peak \(peak) — the soundtrack decoded to near silence")
    #expect(peak <= 1.01)

    let frequency = dominantFrequency(audio)
    #expect(abs(frequency - 440) < 20, "\(name): \(frequency) Hz where the tone is 440")
}

/// A movie with a second soundtrack — another language, a commentary — marks
/// the one a player should use as *enabled*, and it need not be the first in the
/// file. The fixture puts a disabled 440 Hz track first and the enabled 660 Hz
/// track second, so decoding "the first audio track" picks the wrong one and
/// reads 440.
@Test func decodesTheEnabledSoundtrackRatherThanTheFirst() async throws {
    let audio = try await AudioFileDecoder.decode(url: fixture("two_soundtracks.mov"))
    let frequency = dominantFrequency(audio)
    #expect(
        abs(frequency - 660) < 20,
        "\(frequency) Hz: decoded the disabled 440 Hz track instead of the enabled 660 Hz one")
}

/// A screen recording or a muted clip: a real video, and nothing to transcribe.
/// It has to fail as *that*, by name, rather than as "could not be read" — the
/// file is perfectly readable, and telling someone otherwise sends them looking
/// for a corrupt file that does not exist.
@Test func aVideoWithNoSoundtrackSaysSo() async {
    await #expect(throws: DecodeError.noAudioTrack) {
        _ = try await AudioFileDecoder.decode(url: fixture("silent_video.mp4"))
    }
}
