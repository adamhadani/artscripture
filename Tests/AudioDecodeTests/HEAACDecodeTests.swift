import AVFoundation
import Foundation
import Testing

@testable import AudioDecode

// HE-AAC is two layers: a core AAC stream at *half* the sample rate, and SBR,
// which rebuilds the top octave on decode. HE-AAC v2 adds parametric stereo, so
// its core is mono as well. The first description CoreMedia gives for such a
// track describes that core — 22050 Hz, and one channel for v2 — while the
// decoder outputs 44100 Hz stereo.
//
// The decoder used to label its output with the core's numbers. Nothing failed:
// the file opened, drew a waveform and played — at half speed, an octave low,
// for twice its real length. v2 was worse, interleaved stereo read as mono, a
// quarter speed. It was found with an Instagram video, whose soundtrack was
// HE-AAC, but nothing about it is video-specific: an HE-AAC `.m4a` did the same.
//
// So each test asserts the three things a listener would notice — the rate the
// samples are played at, how long the track is, and what pitch comes out — and
// the pitch is measured *at the labelled rate*, which is exactly how playback
// will hear it.

private func fixture(_ name: String) -> URL {
    URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()  // AudioDecodeTests
        .deletingLastPathComponent()  // Tests
        .appendingPathComponent("Fixtures")
        .appendingPathComponent(name)
}

/// Dominant frequency of channel `channel`, from zero crossings over the middle
/// half of the file, counted against the *labelled* sample rate — so a track
/// labelled at half its real rate reads an octave low, as it would sound.
private func dominantFrequency(_ audio: DecodedAudio, channel: Int = 0) -> Double {
    let samples = audio.channel(channel)
    let frames = Int(audio.frameCount)
    let start = frames / 4
    let end = frames - frames / 4
    var crossings = 0
    for i in (start + 1)..<end where (samples[i - 1] < 0) != (samples[i] < 0) {
        crossings += 1
    }
    return Double(crossings) / 2 / (Double(end - start) / audio.sampleRate)
}

/// Generated by `Tests/Fixtures/generate.sh` from the same 2 s, 440 Hz stereo
/// master as every other fixture.
@Test(arguments: ["sine_he_aac.m4a", "sine_he_aac_v2.m4a", "sine_he_aac_video.mp4"])
func heAACIsLabelledWithTheRateAndChannelsItDecodesTo(name: String) async throws {
    let audio = try await AudioFileDecoder.decode(url: fixture(name))

    #expect(audio.sampleRate == 44100, "\(name): labelled \(audio.sampleRate) Hz")
    #expect(audio.channels == 2, "\(name): \(audio.channels) channel(s)")

    let seconds = Double(audio.frameCount) / audio.sampleRate
    #expect(abs(seconds - 2.0) < 0.1, "\(name): \(seconds) s long, where the tone is 2 s")

    let frequency = dominantFrequency(audio)
    #expect(abs(frequency - 440) < 20, "\(name): plays at \(frequency) Hz, where the tone is 440")
}

// MARK: - The decoded buffers must agree with the label

private func lpcm(rate: Double, channels: UInt32) -> AudioStreamBasicDescription {
    AudioStreamBasicDescription(
        mSampleRate: rate, mFormatID: kAudioFormatLinearPCM,
        mFormatFlags: kAudioFormatFlagIsFloat | kAudioFormatFlagIsPacked,
        mBytesPerPacket: 4 * channels, mFramesPerPacket: 1, mBytesPerFrame: 4 * channels,
        mChannelsPerFrame: channels, mBitsPerChannel: 32, mReserved: 0)
}

/// The second line of defence. Choosing the right layer is the fix; this is what
/// makes the *next* codec with the same trap fail loudly, by name, instead of
/// opening and playing at the wrong speed in silence.
@Test func decodedBuffersThatMatchTheLabelAreAccepted() throws {
    try AudioFileDecoder.verifyDecodedLayout(
        lpcm(rate: 44100, channels: 2), sampleRate: 44100, channels: 2)
}

/// The same guard, end to end: a decode whose label is wrong must be refused, not
/// returned. Without this, `verifyDecodedLayout` could be correct, tested, and
/// called from nowhere — the tests above would all stay green.
///
/// The label is forced to HE-AAC's core numbers on a plain AAC file that decodes
/// at 44100 Hz stereo: precisely the mislabel this file is about, now caught.
@Test func aDecodeWhoseLabelDisagreesWithItsSamplesIsRefused() async {
    await #expect(throws: DecodeError.self) {
        _ = try await AudioFileDecoder.decode(
            url: fixture("sine.m4a"), progress: nil, initialCapacityHint: nil,
            labelOverride: (sampleRate: 22050, channels: 2))
    }
}

@Test(arguments: [(22050.0, UInt32(2)), (44100.0, UInt32(1)), (48000.0, UInt32(2))])
func decodedBuffersThatDisagreeWithTheLabelAreRefused(rate: Double, channels: UInt32) {
    #expect(throws: DecodeError.self) {
        try AudioFileDecoder.verifyDecodedLayout(
            lpcm(rate: 44100, channels: 2), sampleRate: rate, channels: Int(channels))
    }
}
